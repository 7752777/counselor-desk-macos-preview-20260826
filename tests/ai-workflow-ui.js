const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { JSDOM, VirtualConsole } = require('jsdom');

const wait = ms => new Promise(resolve => setTimeout(resolve, ms));

(async () => {
  const errors = [];
  const virtualConsole = new VirtualConsole();
  virtualConsole.on('jsdomError', error => { if (!/scrollTo|Could not load|Not implemented/i.test(error.message)) errors.push(error.message); });
  const root = path.join(__dirname, '..');
  const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8')
    .replace('<script defer src="src/core/cwb-ai.js" data-cwb-ai></script>', `<script>${fs.readFileSync(path.join(root, 'src', 'core', 'cwb-ai.js'), 'utf8')}</script>`)
    .replace('<script defer src="src/core/cwb-ai-workflow.js" data-cwb-ai-workflow></script>', `<script>${fs.readFileSync(path.join(root, 'src', 'core', 'cwb-ai-workflow.js'), 'utf8')}</script>`);
  const dom = new JSDOM(html, {
    runScripts:'dangerously', resources:'usable', url:'https://ai-workflow.local/', pretendToBeVisual:true, virtualConsole,
  });
  await wait(750);
  const { CWB } = dom.window;
  assert.ok(CWB.ai && typeof CWB.ai.run === 'function', 'AI workflow API should be exposed');
  assert.equal(typeof CWB.utils.copyTextToClipboard, 'function', 'copy helper should be exposed for consistent UI fallbacks');
  let copiedText = '';
  Object.defineProperty(dom.window.navigator, 'clipboard', { configurable:true, value:{ writeText:async value => { copiedText = value; } } });
  assert.equal(await CWB.utils.copyTextToClipboard('clipboard success'), true);
  assert.equal(copiedText, 'clipboard success');
  Object.defineProperty(dom.window.navigator, 'clipboard', { configurable:true, value:{ writeText:async () => { throw new Error('clipboard denied'); } } });
  dom.window.document.execCommand = command => command === 'copy';
  assert.equal(await CWB.utils.copyTextToClipboard('fallback success'), true);
  assert.equal(await CWB.utils.copyTextToClipboard(''), false);
  const provider = { id:'provider-1', key:'custom', model:'demo', enabled:true, allowedPurposes:['work_summary'], dailyQuota:1 };
  CWB.db.custom.v4_ai_providers = [provider];
  await assert.rejects(() => CWB.ai.run({ provider, purpose:'unregistered_purpose', records:[], send:async () => ({ text:'不应发送' }) }), /AI_PURPOSE_INVALID/, 'unknown AI purposes must fail closed instead of becoming work_summary');
  await assert.rejects(() => CWB.ai.run({ provider, purpose:'certificate_recognition', records:[], send:async () => ({ text:'ignored' }) }), /AI_PURPOSE_NOT_ALLOWED/);
  assert.equal(CWB.db.custom.v4_ai_audit.at(-1).status, 'failed');
  assert.equal((CWB.db.custom.v4_ai_drafts || []).length, 0);
  const relayProvider = { id:'provider-relay', key:'custom', model:'demo', enabled:true, allowedPurposes:['notice_rewrite'], dailyQuota:5, relayUrl:'https://relay.example.test/api/ai/chat' };
  CWB.db.custom.v4_ai_providers.push(relayProvider);
  dom.window.sessionStorage.setItem('cwb_ai_relay_token_provider-relay', 'relay-token-test');
  const originalSendChat = dom.window.CWBAI.sendChat;
  let relayOptions;
  dom.window.CWBAI.sendChat = async (_config, _messages, options) => { relayOptions = options; return { text:'relay-workflow-ok' }; };
  const relayResult = await CWB.ai.run({ provider:relayProvider, purpose:'notice_rewrite', records:[], apiKey:'test-key-not-real', createDraft:false });
  assert.equal(relayResult.result.text, 'relay-workflow-ok');
  assert.equal(relayOptions.relayToken, 'relay-token-test');
  assert.equal(CWB.db.custom.v4_ai_providers[1].relay_token, undefined);
  dom.window.CWBAI.sendChat = originalSendChat;
  dom.window.sessionStorage.removeItem('cwb_ai_relay_token_provider-relay');
  const result = await CWB.ai.run({ provider, purpose:'work_summary', records:[], send:async () => ({ text:'本周完成两项工作' }) });
  assert.equal(result.draft.payload.text, '本周完成两项工作');
  assert.equal(CWB.db.custom.v4_ai_drafts.length, 1);
  assert.equal(CWB.db.custom.v4_ai_audit.at(-1).status, 'completed');
  await assert.rejects(() => CWB.ai.run({ provider, purpose:'work_summary', records:[], send:async () => ({ text:'ignored' }) }), /AI_DAILY_QUOTA_EXCEEDED/);
  const uiProvider = { id:'ui-retry-provider', key:'custom', model:'ui-demo', enabled:true, secret_set:true, allowedPurposes:['work_summary'], dailyQuota:50 };
  CWB.db.custom.v4_ai_providers = [uiProvider];
  const uiSuggestion = CWB.ai.suggestions.create({ purpose:'work_summary', title:'UI 批量查看测试', summary:'仅测试建议中心控件', risk_level:'critical', payload:{ text:'仅测试建议中心控件' } });
  const warningSuggestion = CWB.ai.suggestions.create({ purpose:'warning_assist', title:'预警用途筛选测试', summary:'用于验证 canonical 用途筛选', payload:{ text:'仅测试筛选' } });
  const certificateSuggestion = CWB.ai.suggestions.create({ purpose:'certificate_recognition', title:'证书用途筛选测试', summary:'用于验证证书用途标签', payload:{ text:'仅测试筛选' } });
  assert.equal(CWB.ai.suggestions.list({ purpose:'risk_review' }).some(item => item.id === warningSuggestion.id), true, 'risk_review alias should filter canonical warning_assist suggestions');
  assert.equal(CWB.ai.suggestions.list({ purpose:'certificate_recognition' }).some(item => item.id === certificateSuggestion.id), true, 'certificate purpose should remain filterable');
  CWB.go('ai');
  assert.ok(dom.window.document.querySelector('[data-ai-suggestion-risk]'), 'suggestion center should expose risk filtering');
  assert.ok(dom.window.document.querySelector('[data-ai-source-status]'), 'source directory should expose verification filtering');
  assert.ok(dom.window.document.querySelector('[data-ai-suggestion-purpose] option[value="warning_assist"]'), 'suggestion center should expose canonical warning purpose');
  assert.ok(dom.window.document.querySelector('[data-ai-suggestion-purpose] option[value="certificate_recognition"]'), 'suggestion center should expose certificate purpose');
  assert.ok(dom.window.document.querySelector('[data-ai-purpose] option[value="warning_assist"]'), 'AI workbench should expose canonical warning purpose');
  assert.ok(dom.window.document.querySelector('[data-ai-purpose] option[value="certificate_recognition"]'), 'AI workbench should expose certificate purpose');
  assert.equal(dom.window.document.querySelector('[data-ai-suggestion-purpose] option[value="warning_assist"]').textContent, '预警辅助分析');
  assert.equal(dom.window.document.querySelector('[data-ai-suggestion-purpose] option[value="certificate_recognition"]').textContent, '证书识别草稿');
  assert.ok(dom.window.document.querySelector('[data-ai-suggestion-select-all]'), 'suggestion center should expose current-result selection');
  assert.ok(dom.window.document.querySelector('[data-act="ai-suggestion-batch-view"]'), 'suggestion center should expose batch viewed action');
  const selectAll = dom.window.document.querySelector('[data-ai-suggestion-select-all]');
  selectAll.checked = true;
  selectAll.dispatchEvent(new dom.window.Event('change', { bubbles:true }));
  await wait(20);
  assert.ok(dom.window.document.querySelector(`[data-ai-suggestion-select][data-id="${uiSuggestion.id}"]`).checked, 'select all should select visible suggestions');
  dom.window.document.querySelector('[data-act="ai-suggestion-batch-view"]').click();
  await wait(20);
  assert.equal(CWB.ai.suggestions.list({ query:'UI 批量查看测试' })[0].status, 'viewed');
  assert.throws(() => CWB.ai.suggestions.accept(uiSuggestion.id), /AI_SUGGESTION_CONFIRM_REQUIRED/);
  assert.equal(CWB.ai.suggestions.accept(uiSuggestion.id, { confirmed:true }).status, 'accepted', 'high-risk acceptance must be explicit');
  dom.window.sessionStorage.removeItem('cwb_ai_secret_ui-retry-provider');
  CWB.go('ai');
  const missingKeyRun = dom.window.document.querySelector('[data-act="ai-run"]');
  assert.equal(missingKeyRun.disabled, true, 'generation should be disabled when the selected provider has no current-session key');
  assert.equal(missingKeyRun.dataset.aiReadinessCode, 'AI_API_KEY_REQUIRED');
  assert.match(dom.window.document.querySelector('[data-ai-provider-readiness]').textContent, /API 密钥|密钥/);
  dom.window.sessionStorage.setItem('cwb_ai_secret_ui-retry-provider', 'test-key-not-real');
  CWB.go('ai');
  let failedCalls = 0;
  const beforeUiSend = dom.window.CWBAI.sendChat;
  dom.window.CWBAI.sendChat = async () => { failedCalls += 1; throw new Error('AI_PROVIDER_NETWORK_UNAVAILABLE'); };
  const prompt = dom.window.document.querySelector('[data-ai-prompt]');
  prompt.value = '测试失败后重试';
  dom.window.document.querySelector('[data-act="ai-run"]').click();
  await wait(220);
  assert.equal(failedCalls, 1);
  CWB.go('ai');
  assert.ok(dom.window.document.querySelector('[data-act="ai-retry"]'), 'failed AI requests should expose a retry action');
  const storedUi = JSON.parse(dom.window.localStorage.getItem('cwb_v1_ui_state') || '{}');
  const retry = storedUi.v4 && storedUi.v4.aiRetry;
  assert.equal(Object.hasOwn(retry, 'prompt'), false, 'retry state must not persist an arbitrary prompt in ui_state');
  assert.ok(retry.request_id, 'retry state should retain a non-secret request identifier');
  assert.equal(Object.hasOwn(retry, 'apiKey'), false, 'retry state must never store an API key');
  assert.equal(JSON.stringify(retry).includes('test-key-not-real'), false, 'retry state must not contain the secret value');
  dom.window.CWBAI.sendChat = async () => ({ text:'一次新的手动生成' });
  const freshPrompt = dom.window.document.querySelector('[data-ai-prompt]');
  freshPrompt.value = '失败后修改提示词重新生成';
  dom.window.document.querySelector('[data-act="ai-run"]').click();
  await wait(180);
  const freshAudit = [...CWB.db.custom.v4_ai_audit].reverse().find(item => item.action === 'generate' && item.status === 'completed');
  assert.ok(freshAudit, 'a manually started request after failure should complete');
  assert.equal(freshAudit.retry_of_audit_id, '', 'a fresh request must not inherit the previous failure retry chain');
  dom.window.CWBAI.sendChat = beforeUiSend;

  CWB.go('ai');
  dom.window.sessionStorage.setItem('cwb_ai_secret_ui-retry-provider', 'test-key-not-real');
  let cancelSignal;
  const pendingSend = dom.window.CWBAI.sendChat;
  dom.window.CWBAI.sendChat = async (_config, _messages, options) => new Promise((_resolve, reject) => {
    cancelSignal = options.signal;
    options.signal.addEventListener('abort', () => reject(new Error('AI_PROVIDER_REQUEST_ABORTED')), { once:true });
  });
  dom.window.document.querySelector('[data-act="ai-run"]').click();
  await wait(40);
  assert.ok(dom.window.document.querySelector('.ai-request-state.is-running'), 'AI generation should expose its running state before the network call settles');
  assert.equal(dom.window.document.querySelector('[data-act="ai-run"]').disabled, true, 'generation controls should be disabled while a request is running');
  assert.equal(dom.window.document.querySelector('[data-act="ai-cancel"]').disabled, false, 'cancel should remain available while a request is running');
  assert.ok(cancelSignal && cancelSignal.aborted === false, 'running request should expose a cancellable signal');
  dom.window.document.querySelector('[data-act="ai-cancel"]').click();
  await wait(40);
  assert.ok(dom.window.document.querySelector('.ai-request-state'), 'cancelled AI request should remain visible for retry');
  assert.equal([...CWB.db.custom.v4_ai_audit].reverse().find(item => item.action === 'generate' && item.request_id === CWB.db.custom.v4_ai_audit.at(-1).request_id).status, 'cancelled', 'cancelled generation must be auditable as cancelled rather than failed');
  dom.window.CWBAI.sendChat = pendingSend;
  dom.window.sessionStorage.removeItem('cwb_ai_secret_ui-retry-provider');
  dom.window.sessionStorage.setItem('cwb_ai_secret_ui-retry-provider', 'test-key-not-real');
  CWB.go('ai');
  await wait(30);
  const purposeSelect = dom.window.document.querySelector('[data-ai-purpose]');
  purposeSelect.value = 'work_summary';
  const identityConsent = dom.window.document.querySelector('[data-ai-sensitive-category="identity"]');
  identityConsent.checked = true;
  let consentCalls = 0;
  const consentSend = dom.window.CWBAI.sendChat;
  dom.window.CWBAI.sendChat = async () => { consentCalls += 1; return { text:'授权后的建议' }; };
  dom.window.document.querySelector('[data-act="ai-run"]').click();
  await wait(30);
  assert.ok(dom.window.document.querySelector('[data-ai-consent-confirm]'), 'sensitive generation must ask for explicit consent');
  assert.equal(consentCalls, 0, 'model request must wait for explicit consent');
  dom.window.document.querySelector('[data-ai-consent-cancel]').click();
  await wait(20);
  assert.equal(consentCalls, 0, 'cancelling consent must not send a request');
  assert.equal(dom.window.document.querySelector('.ai-request-state.is-running'), null, 'cancelling consent must clear the running request state');
  assert.equal(dom.window.document.querySelector('[data-act="ai-run"]').disabled, false, 'cancelling consent should restore generation controls');
  dom.window.document.querySelector('[data-act="ai-run"]').click();
  await wait(20);
  dom.window.document.querySelector('[data-ai-consent-confirm]').click();
  await wait(140);
  assert.equal(consentCalls, 1, 'confirmed consent should allow exactly one request');
  assert.ok(CWB.db.custom.v4_ai_consents.at(-1).used_at, 'confirmed consent should be consumed');
  dom.window.CWBAI.sendChat = consentSend;
  dom.window.sessionStorage.removeItem('cwb_ai_secret_ui-retry-provider');
  CWB.go('tasks');
  assert.ok(dom.window.document.querySelectorAll('[data-act="ai-inline"]').length >= 2, 'core pages should expose more than one contextual AI action');
  CWB.go('ai');
  assert.equal(dom.window.document.querySelectorAll('[data-ai-suggestion-status],[data-ai-suggestion-purpose],[data-ai-suggestion-risk],[data-ai-suggestion-source]').length, 4, 'suggestion filters must remain independent controls');
  const staleSource = dom.window.CWBAIWorkflow.normalizeSource({ id:'ui-stale-source', kind:'web', url:'https://example.com/stale', title:'需要核验的网页', excerpt:'旧片段', status:'needs_review', verification_status:'needs_review', verification_error:'AI_SOURCE_TIMEOUT' });
  CWB.db.custom.v4_ai_sources.push(staleSource);
  const originalRevalidate = dom.window.CWBAI.revalidatePublicSource;
  dom.window.CWBAI.revalidatePublicSource = async input => ({ id:input.id, url:input.url, title:'重新核验成功', excerpt:'最新来源片段', retrieved_at:new Date().toISOString(), status:'available', verification_status:'verified' });
  const refreshedSource = await CWB.ai.sources.revalidate({ id:staleSource.id });
  assert.equal(refreshedSource.verification_status, 'verified');
  assert.equal(CWB.db.custom.v4_ai_sources.find(item => item.id === staleSource.id).verification_status, 'verified');
  dom.window.CWBAI.revalidatePublicSource = async () => { throw new Error('AI_SOURCE_TIMEOUT'); };
  await assert.rejects(() => CWB.ai.sources.revalidate({ id:staleSource.id }), /AI_SOURCE_TIMEOUT/);
  assert.equal(CWB.db.custom.v4_ai_sources.find(item => item.id === staleSource.id).verification_status, 'needs_review');
  dom.window.CWBAI.revalidatePublicSource = originalRevalidate;
  assert.deepEqual(errors, []);
  dom.window.close();
  console.log('PASS ai-workflow-ui');
})().catch(error => { console.error(error.stack || error); process.exitCode = 1; });
